import { spawnSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import os from "node:os";

const REPO = "D:/Workspaces/Astesia";
const RULES = join(REPO, "templates/enforcement/anti-patterns.json");
const tempDir = join(os.tmpdir(), `test-bypass-${Date.now()}`);
mkdirSync(tempDir, { recursive: true });

// (i) 300 normal lines + one comment 6000 chars + violations
let content1 = "";
for (let i = 0; i < 300; i++) {
  content1 += `const val${i} = ${i};\n`;
}
content1 += `// ` + "A".repeat(6000) + `\n`;
content1 += `const x: any = 1;\n`;
content1 += `console.log("hello");\n`;
content1 += `const q = "SELECT * FROM users";\n`;
writeFileSync(join(tempDir, "file1.ts"), content1);

// (ii) // @generated + one line 500 chars + violations
let content2 = `// @generated by tool\n`;
content2 += `const longLine = "${"B".repeat(500)}";\n`;
content2 += `const x: any = 1;\n`;
content2 += `console.log("hello");\n`;
content2 += `const q = "SELECT * FROM users";\n`;
writeFileSync(join(tempDir, "file2.ts"), content2);

try {
  const res = spawnSync("bun", [join(REPO, "templates/enforcement/astesia-gate.ts"), "--root", tempDir, "--rules", RULES, "--json"], { encoding: "utf8" });
  console.log("Exit code:", res.status);
  const out = JSON.parse(res.stdout);
  console.log("Generated skipped:", out.generated_skipped);
  console.log("Generated files:", out.generated_files);
  console.log("Notices:", out.notices);
  console.log("Violations found:");
  for (const v of out.violations) {
    console.log(`  [${v.ruleId}] ${v.file}:${v.line} - ${v.message}`);
  }
} finally {
  try { rmSync(tempDir, { recursive: true, force: true }); } catch {}
}
