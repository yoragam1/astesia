import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

export function runGeneratedPolicyV2Suite(
  customGatePath?: string,
  customTmpDir?: string
): { total: number; passed: number; failed: number; known_gaps: number; errors: string[] } {
  const gatePath = customGatePath || resolve(__dirname, "../astesia-gate.ts");
  const rulesPath = resolve(__dirname, "../anti-patterns.json");
  const baseTmp = customTmpDir || resolve(__dirname, "../../../.astesia/audit/tmp/gen-v2-" + Date.now());
  mkdirSync(baseTmp, { recursive: true });

  let passed = 0;
  let failed = 0;
  const errors: string[] = [];

  function record(id: string, name: string, ok: boolean, detail: string) {
    if (ok) {
      passed++;
    } else {
      failed++;
      errors.push(`FAIL: ${id} (${name}) - ${detail}`);
    }
  }

  function runGate(dir: string, extraArgs: string[] = []) {
    const start = performance.now();
    const res = spawnSync(process.execPath, [gatePath, "--root", dir, "--rules", rulesPath, ...extraArgs], {
      encoding: "utf8",
      maxBuffer: 50 * 1024 * 1024
    });
    const elapsedMs = performance.now() - start;
    let json: any = null;
    try {
      json = JSON.parse(res.stdout);
    } catch {}
    return { status: res.status, stdout: res.stdout, stderr: res.stderr, json, elapsedMs };
  }

  try {
    // GP2-01: Comment bomb: 300 normal lines + one 6,000 char comment line, ratio < 50% -> NOT generated, violations detected
    {
      const d = join(baseTmp, "gp2_01");
      mkdirSync(d, { recursive: true });
      const normalLines = Array.from({ length: 300 }, (_, i) => `const val_${i} = ${i};`);
      const commentBomb = "// " + "A".repeat(6000);
      const viols = [
        "const a: any = 1;",
        'console.log("hello");',
        'const q = "SELECT * FROM users";'
      ];
      writeFileSync(join(d, "bomb.ts"), [...normalLines, commentBomb, ...viols].join("\n"), "utf8");
      const r = runGate(d, ["--json"]);
      const vIds = (r.json?.violations || []).map((v: any) => v.ruleId);
      const ok =
        r.json?.generated_skipped === 0 &&
        vIds.includes("ASTESIA-005") &&
        vIds.includes("ASTESIA-006") &&
        vIds.includes("ASTESIA-002");
      record("GP2-01", "Comment bomb NOT skipped and violations detected", ok, JSON.stringify(r.json));
    }

    // GP2-02: Header @generated on hand-written file -> scanned fully, notice generated_header_candidates emitted
    {
      const d = join(baseTmp, "gp2_02");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "client.ts"), "// @generated by tool\nexport const bad: any = 1;\n", "utf8");
      const r = runGate(d, ["--json"]);
      const viols = r.json?.violations || [];
      const notices = r.json?.notices?.generated_header_candidates || [];
      const ok =
        r.json?.generated_skipped === 0 &&
        r.json?.files_scanned?.total === 1 &&
        viols.some((v: any) => v.ruleId === "ASTESIA-005") &&
        notices.some((n: any) => (typeof n === "string" ? n.includes("client.ts") : n.file?.includes("client.ts")));
      record("GP2-02", "Header @generated scanned fully with notice", ok, JSON.stringify(r.json));
    }

    // GP2-03: Header DO NOT EDIT on line 5 -> scanned fully with notice
    {
      const d = join(baseTmp, "gp2_03");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "schema.ts"), "// L1\n// L2\n// L3\n// L4\n// DO NOT EDIT THIS FILE\nexport const bad: any = 1;\n", "utf8");
      const r = runGate(d, ["--json"]);
      const viols = r.json?.violations || [];
      const notices = r.json?.notices?.generated_header_candidates || [];
      const ok =
        r.json?.generated_skipped === 0 &&
        viols.some((v: any) => v.ruleId === "ASTESIA-005") &&
        notices.some((n: any) => (typeof n === "string" ? n.includes("schema.ts") : n.file?.includes("schema.ts")));
      record("GP2-03", "Header DO NOT EDIT on line 5 scanned fully with notice", ok, JSON.stringify(r.json));
    }

    // GP2-04: Header Code generated on line 10 -> scanned fully with notice
    {
      const d = join(baseTmp, "gp2_04");
      mkdirSync(d, { recursive: true });
      const lines = Array.from({ length: 9 }, (_, i) => `// line ${i + 1}`).join("\n") + "\n// Code generated by protoc\nexport const bad: any = 1;\n";
      writeFileSync(join(d, "proto.ts"), lines, "utf8");
      const r = runGate(d, ["--json"]);
      const viols = r.json?.violations || [];
      const notices = r.json?.notices?.generated_header_candidates || [];
      const ok =
        r.json?.generated_skipped === 0 &&
        viols.some((v: any) => v.ruleId === "ASTESIA-005") &&
        notices.some((n: any) => (typeof n === "string" ? n.includes("proto.ts") : n.file?.includes("proto.ts")));
      record("GP2-04", "Header Code generated on line 10 scanned fully with notice", ok, JSON.stringify(r.json));
    }

    // GP2-05: Header @generated on line 11 -> scanned fully, NO header notice
    {
      const d = join(baseTmp, "gp2_05");
      mkdirSync(d, { recursive: true });
      const lines = Array.from({ length: 10 }, (_, i) => `// line ${i + 1}`).join("\n") + "\n// @generated too late\nexport const bad: any = 1;\n";
      writeFileSync(join(d, "not_hdr.ts"), lines, "utf8");
      const r = runGate(d, ["--json"]);
      const notices = r.json?.notices?.generated_header_candidates || [];
      const ok = notices.length === 0;
      record("GP2-05", "Header marker on line 11 emits no notice", ok, JSON.stringify(r.json));
    }

    // GP2-06: Minified single-line file (1 line 10,000 chars, ratio 100%) -> skipped as generated
    {
      const d = join(baseTmp, "gp2_06");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "bundle.js"), "var a=" + "1,".repeat(5000) + "b=2;\n", "utf8");
      const r = runGate(d, ["--json"]);
      const ok = r.status === 0 && r.json?.generated_skipped === 1 && r.json?.generated_files?.includes("bundle.js");
      record("GP2-06", "Single-line minified file is skipped as generated", ok, JSON.stringify(r.json));
    }

    // GP2-07: Ratio boundary 49.9% -> NOT generated
    {
      const d = join(baseTmp, "gp2_07");
      mkdirSync(d, { recursive: true });
      const line5000 = "x".repeat(5000); // 5000 bytes
      const normalLines = Array.from({ length: 51 }, () => "y".repeat(100)); // 51 * 101 bytes = 5151 bytes
      // Total bytes ~ 10,152 bytes. Line >= 1000 bytes is only line5000 (5001 bytes). Ratio = 5001 / 10152 = 49.26% < 50%
      writeFileSync(join(d, "border49.ts"), [line5000, ...normalLines, "export const bad: any = 1;"].join("\n"), "utf8");
      const r = runGate(d, ["--json"]);
      const viols = r.json?.violations || [];
      const ok = r.json?.generated_skipped === 0 && viols.some((v: any) => v.ruleId === "ASTESIA-005");
      record("GP2-07", "Ratio 49.9% is NOT generated", ok, JSON.stringify(r.json));
    }

    // GP2-08: Ratio boundary 50.0% -> IS generated
    {
      const d = join(baseTmp, "gp2_08");
      mkdirSync(d, { recursive: true });
      const line5000 = "x".repeat(5000); // 5001 bytes with newline
      const normalLines = Array.from({ length: 48 }, () => "y".repeat(100)); // 48 * 101 bytes = 4848 bytes
      // Total bytes = 5001 + 4848 = 9849 bytes. Ratio = 5001 / 9849 = 50.78% >= 50%
      writeFileSync(join(d, "border50.ts"), [line5000, ...normalLines].join("\n"), "utf8");
      const r = runGate(d, ["--json"]);
      const ok = r.status === 0 && r.json?.generated_skipped === 1 && r.json?.generated_files?.includes("border50.ts");
      record("GP2-08", "Ratio 50.0% is generated", ok, JSON.stringify(r.json));
    }

    // GP2-09: Line length boundary 4,999 chars with 100% ratio -> NOT generated
    {
      const d = join(baseTmp, "gp2_09");
      mkdirSync(d, { recursive: true });
      const line4999 = "const a = '" + "x".repeat(4980) + "';"; // exactly 4999 chars
      writeFileSync(join(d, "line4999.ts"), line4999 + "\nexport const bad: any = 1;\n", "utf8");
      const r = runGate(d, ["--json"]);
      const viols = r.json?.violations || [];
      const ok = r.json?.generated_skipped === 0 && viols.some((v: any) => v.ruleId === "ASTESIA-005");
      record("GP2-09", "Line 4999 chars is NOT generated even if 100% ratio", ok, JSON.stringify(r.json));
    }

    // GP2-10: Line length boundary 5,000 chars with 100% ratio -> IS generated
    {
      const d = join(baseTmp, "gp2_10");
      mkdirSync(d, { recursive: true });
      const line5000 = "const a = '" + "x".repeat(5000) + "';"; // >= 5000 chars
      writeFileSync(join(d, "line5000.ts"), line5000 + "\n", "utf8");
      const r = runGate(d, ["--json"]);
      const ok = r.status === 0 && r.json?.generated_skipped === 1 && r.json?.generated_files?.includes("line5000.ts");
      record("GP2-10", "Line 5000 chars with 100% ratio is generated", ok, JSON.stringify(r.json));
    }

    // GP2-11: .min.js short file -> IS generated
    {
      const d = join(baseTmp, "gp2_11");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "app.min.js"), "console.log('short');\n", "utf8");
      const r = runGate(d, ["--json"]);
      const ok = r.status === 0 && r.json?.generated_skipped === 1 && r.json?.generated_files?.includes("app.min.js");
      record("GP2-11", ".min.js short file is generated", ok, JSON.stringify(r.json));
    }

    // GP2-12: .min.mjs short file -> IS generated
    {
      const d = join(baseTmp, "gp2_12");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "app.min.mjs"), "console.log('short');\n", "utf8");
      const r = runGate(d, ["--json"]);
      const ok = r.status === 0 && r.json?.generated_skipped === 1 && r.json?.generated_files?.includes("app.min.mjs");
      record("GP2-12", ".min.mjs short file is generated", ok, JSON.stringify(r.json));
    }

    // GP2-13: .min.cjs short file -> IS generated
    {
      const d = join(baseTmp, "gp2_13");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "app.min.cjs"), "console.log('short');\n", "utf8");
      const r = runGate(d, ["--json"]);
      const ok = r.status === 0 && r.json?.generated_skipped === 1 && r.json?.generated_files?.includes("app.min.cjs");
      record("GP2-13", ".min.cjs short file is generated", ok, JSON.stringify(r.json));
    }

    // GP2-14: .min.css short file -> IS generated
    {
      const d = join(baseTmp, "gp2_14");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "app.min.css"), "body{color:red;}\n", "utf8");
      const r = runGate(d, ["--json"]);
      const ok = r.status === 0 && r.json?.generated_skipped === 1 && r.json?.generated_files?.includes("app.min.css");
      record("GP2-14", ".min.css short file is generated", ok, JSON.stringify(r.json));
    }

    // GP2-15: Strong-prefix secret at EOF of 1,000,000-char line in generated file -> detected
    {
      const d = join(baseTmp, "gp2_15");
      mkdirSync(d, { recursive: true });
      const pad = "x".repeat(1000000);
      writeFileSync(join(d, "huge.min.js"), pad + ',"sk_live_1234567890abcdef"\n', "utf8");
      const r = runGate(d, ["--json"]);
      const viols = r.json?.violations || [];
      const ok = viols.some((v: any) => v.ruleId === "ASTESIA-004");
      record("GP2-15", "Strong prefix secret at EOF of 1M chars detected", ok, JSON.stringify(r.json));
    }

    // GP2-16: Swap attack: baseline has A.js, new scan has B.js (same count = 1) -> exit 1!
    {
      const d = join(baseTmp, "gp2_16");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "B.min.js"), "var b=1;\n", "utf8");
      const baseline = {
        schema: 1,
        generated_at: new Date().toISOString(),
        counters: {
          debt_markers: 0,
          suppressions: 0,
          files_excluded: 0,
          desync_files: 0,
          generated_skipped: 1
        },
        generated_files: ["A.min.js"],
        violations: {}
      };
      writeFileSync(join(d, ".astesia-baseline.json"), JSON.stringify(baseline, null, 2), "utf8");
      const r = runGate(d, ["--baseline", join(d, ".astesia-baseline.json")]);
      const ok = r.status === 1;
      record("GP2-16", "Swap attack (same count, different path) exits 1", ok, `status=${r.status}, stdout=${r.stdout}`);
    }

    // GP2-17: Baseline without generated_files key (legacy) + generated file present -> exit 1
    {
      const d = join(baseTmp, "gp2_17");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "file.min.js"), "var a=1;\n", "utf8");
      const legacyBaseline = {
        schema: 1,
        generated_at: new Date().toISOString(),
        counters: {
          debt_markers: 0,
          suppressions: 0,
          files_excluded: 0,
          desync_files: 0,
          generated_skipped: 1
        },
        violations: {}
      };
      writeFileSync(join(d, ".astesia-baseline.json"), JSON.stringify(legacyBaseline, null, 2), "utf8");
      const r = runGate(d, ["--baseline", join(d, ".astesia-baseline.json")]);
      const ok = r.status === 1;
      record("GP2-17", "Legacy baseline without generated_files rejects unlisted generated file", ok, `status=${r.status}`);
    }

    // GP2-18: Baseline with matching generated_files -> exit 0
    {
      const d = join(baseTmp, "gp2_18");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "app.min.js"), "var a=1;\n", "utf8");
      const matchingBaseline = {
        schema: 1,
        generated_at: new Date().toISOString(),
        counters: {
          debt_markers: 0,
          suppressions: 0,
          files_excluded: 0,
          desync_files: 0,
          generated_skipped: 1
        },
        generated_files: ["app.min.js"],
        violations: {}
      };
      writeFileSync(join(d, ".astesia-baseline.json"), JSON.stringify(matchingBaseline, null, 2), "utf8");
      const r = runGate(d, ["--baseline", join(d, ".astesia-baseline.json")]);
      const ok = r.status === 0;
      record("GP2-18", "Matching generated_files baseline exits 0", ok, `status=${r.status}`);
    }

    // GP2-19: --update-baseline adding generated file without --allow-raise -> exit 1
    {
      const d = join(baseTmp, "gp2_19");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "new.min.js"), "var n=1;\n", "utf8");
      const baseline = {
        schema: 1,
        generated_at: new Date().toISOString(),
        counters: { debt_markers: 0, suppressions: 0, files_excluded: 0, desync_files: 0, generated_skipped: 0 },
        generated_files: [],
        violations: {}
      };
      writeFileSync(join(d, ".astesia-baseline.json"), JSON.stringify(baseline, null, 2), "utf8");
      const r = runGate(d, ["--update-baseline", join(d, ".astesia-baseline.json")]);
      const ok = r.status === 1;
      record("GP2-19", "--update-baseline adding generated file without --allow-raise exits 1", ok, `status=${r.status}`);
    }

    // GP2-20: --update-baseline with --allow-raise but short reason (<15 chars) -> exit 1
    {
      const d = join(baseTmp, "gp2_20");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "new.min.js"), "var n=1;\n", "utf8");
      const baseline = {
        schema: 1,
        generated_at: new Date().toISOString(),
        counters: { debt_markers: 0, suppressions: 0, files_excluded: 0, desync_files: 0, generated_skipped: 0 },
        generated_files: [],
        violations: {}
      };
      writeFileSync(join(d, ".astesia-baseline.json"), JSON.stringify(baseline, null, 2), "utf8");
      const r = runGate(d, [
        "--update-baseline", join(d, ".astesia-baseline.json"),
        "--allow-raise",
        "--reason", "short reason"
      ]);
      const ok = r.status === 2;
      record("GP2-20", "--allow-raise with reason < 15 chars exits 2", ok, `status=${r.status}`);
    }

    // GP2-21: --update-baseline with valid --allow-raise --reason (>= 15 chars) -> exit 0 and recorded in history
    {
      const d = join(baseTmp, "gp2_21");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "new.min.js"), "var n=1;\n", "utf8");
      const baseline = {
        schema: 1,
        generated_at: new Date().toISOString(),
        counters: { debt_markers: 0, suppressions: 0, files_excluded: 0, desync_files: 0, generated_skipped: 0 },
        generated_files: [],
        violations: {}
      };
      writeFileSync(join(d, ".astesia-baseline.json"), JSON.stringify(baseline, null, 2), "utf8");
      const r = runGate(d, [
        "--update-baseline", join(d, ".astesia-baseline.json"),
        "--allow-raise",
        "--reason", "Legitimate new minified vendor library"
      ]);
      let saved: any = null;
      try {
        saved = JSON.parse(require("node:fs").readFileSync(join(d, ".astesia-baseline.json"), "utf8"));
      } catch {}
      const ok =
        r.status === 0 &&
        saved?.generated_files?.includes("new.min.js") &&
        Array.isArray(saved?.history) &&
        saved.history.length > 0;
      record("GP2-21", "Valid --allow-raise updates baseline and records history", ok, `status=${r.status}`);
    }

    // GP2-22: Tightening: removing generated file path from baseline without --allow-raise -> exit 0
    {
      const d = join(baseTmp, "gp2_22");
      mkdirSync(d, { recursive: true });
      // Directory has no files!
      const baseline = {
        schema: 1,
        generated_at: new Date().toISOString(),
        counters: { debt_markers: 0, suppressions: 0, files_excluded: 0, desync_files: 0, generated_skipped: 1 },
        generated_files: ["old.min.js"],
        violations: {}
      };
      writeFileSync(join(d, ".astesia-baseline.json"), JSON.stringify(baseline, null, 2), "utf8");
      const r = runGate(d, [
        "--update-baseline", join(d, ".astesia-baseline.json")
      ]);
      let saved: any = null;
      try {
        saved = JSON.parse(require("node:fs").readFileSync(join(d, ".astesia-baseline.json"), "utf8"));
      } catch {}
      const ok = r.status === 0 && saved?.generated_files?.length === 0;
      record("GP2-22", "Removing generated file (tighten) allowed without --allow-raise", ok, `status=${r.status}`);
    }

    // GP2-23: Windows backslash normalized to posix forward slash in generated_files
    {
      const d = join(baseTmp, "gp2_23");
      mkdirSync(join(d, "sub/dir"), { recursive: true });
      writeFileSync(join(d, "sub/dir/app.min.js"), "var a=1;\n", "utf8");
      const r = runGate(d, ["--json"]);
      const ok =
        r.json?.generated_files?.length === 1 &&
        r.json.generated_files[0] === "sub/dir/app.min.js" &&
        !r.json.generated_files[0].includes("\\");
      record("GP2-23", "Nested generated file path uses posix slash", ok, JSON.stringify(r.json));
    }

    // GP2-24: CRLF file byte calculation normalized
    {
      const d = join(baseTmp, "gp2_24");
      mkdirSync(d, { recursive: true });
      const line5000 = "x".repeat(5000);
      const content = line5000 + "\r\n" + "y".repeat(100) + "\r\n";
      writeFileSync(join(d, "crlf.ts"), content, "utf8");
      const r = runGate(d, ["--json"]);
      const ok = r.status === 0 && r.json?.generated_skipped === 1 && r.json?.generated_files?.includes("crlf.ts");
      record("GP2-24", "CRLF file byte counting normalized to LF", ok, JSON.stringify(r.json));
    }

    // GP2-25: ReDoS performance: 1,000,000 chars < 1500 ms
    {
      const d = join(baseTmp, "gp2_25");
      mkdirSync(d, { recursive: true });
      const bigLine = "a".repeat(1000000);
      writeFileSync(join(d, "big.min.js"), bigLine + "\n", "utf8");
      const r = runGate(d, ["--json"]);
      const ok = r.status === 0 && r.elapsedMs < 1500;
      record("GP2-25", "ReDoS on 1M chars completes in < 1500 ms", ok, `elapsed=${r.elapsedMs}ms`);
    }

    // GP2-26: Multiple generated files are lexicographically sorted in generated_files
    {
      const d = join(baseTmp, "gp2_26");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "z.min.js"), "var z=1;\n", "utf8");
      writeFileSync(join(d, "a.min.js"), "var a=1;\n", "utf8");
      writeFileSync(join(d, "m.min.js"), "var m=1;\n", "utf8");
      const r = runGate(d, ["--json"]);
      const list = r.json?.generated_files || [];
      const ok = list.length === 3 && list[0] === "a.min.js" && list[1] === "m.min.js" && list[2] === "z.min.js";
      record("GP2-26", "Generated files list is sorted lexicographically", ok, JSON.stringify(list));
    }

    // GP2-27: Notice generated_header_candidates suggests config exclude
    {
      const d = join(baseTmp, "gp2_27");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "auto.ts"), "// @generated\nexport const x = 1;\n", "utf8");
      const r = runGate(d, []);
      const ok = r.stdout.includes("generated_header_candidates") || r.stdout.includes("@generated") || r.stdout.includes("exclude");
      record("GP2-27", "Text output surfaces notice suggesting config exclude", ok, r.stdout.slice(0, 300));
    }

    // GP2-28: Strong secret ghp_ in comment bomb file detected
    {
      const d = join(baseTmp, "gp2_28");
      mkdirSync(d, { recursive: true });
      const commentBomb = "// " + "A".repeat(6000) + "\nconst token = 'ghp_ABCDEFGHIJKLMNOPQRSTUVWXYZ123456';\n";
      writeFileSync(join(d, "bomb_secret.ts"), commentBomb, "utf8");
      const r = runGate(d, ["--json"]);
      const viols = r.json?.violations || [];
      const ok = viols.some((v: any) => v.ruleId === "ASTESIA-004");
      record("GP2-28", "Strong secret detected in comment-bombed file", ok, JSON.stringify(r.json));
    }

    // GP2-29: --json includes notices.generated_header_candidates with file and marker
    {
      const d = join(baseTmp, "gp2_29");
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, "gen.ts"), "// @generated by protobuf\nexport const p = 1;\n", "utf8");
      const r = runGate(d, ["--json"]);
      const notices = r.json?.notices?.generated_header_candidates || [];
      const entry = notices.find((n: any) => (typeof n === "string" ? n.includes("gen.ts") : n.file?.includes("gen.ts")));
      const ok = entry !== undefined;
      record("GP2-29", "--json notices.generated_header_candidates includes entry", ok, JSON.stringify(r.json?.notices));
    }
  } finally {
    try {
      rmSync(baseTmp, { recursive: true, force: true });
    } catch {}
  }

  return { total: passed + failed, passed, failed, known_gaps: 0, errors };
}

if (import.meta.main) {
  const result = runGeneratedPolicyV2Suite();
  console.log(`Generated Policy v2 Suite: ${result.passed}/${result.total} passed (${result.failed} failed)`);
  if (result.errors.length > 0) {
    console.error(result.errors.join("\n"));
    process.exit(1);
  }
}
